"""Generate dark-mode overrides for every rule in css/glass.css that hardcodes a light surface or dark text.
Writes the block between the AUTO-DARK markers in css/polish.css (re-run after changing glass.css)."""
import re, sys
src = open(sys.argv[1]).read(); out_path = sys.argv[2]
src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
def lum(h):
    h = h.lstrip('#'); h = ''.join(c*2 for c in h) if len(h) == 3 else h[:6]
    r, g, b = (int(h[i:i+2], 16) for i in (0, 2, 4)); return (0.2126*r + 0.7152*g + 0.0722*b) / 255, (r, g, b)
TEXT = {'green': '#8fe0b5', 'red': '#ff9f8c', 'blue': '#b9d4f2', 'amber': '#f0cc7a', 'ink': 'var(--ink)'}
def text_map(h):
    l, (r, g, b) = lum(h)
    if l > .45: return None
    if max(r, g, b) - min(r, g, b) < 40: return TEXT['ink']
    if g >= r and g >= b: return TEXT['green']
    if r >= g and r >= b: return TEXT['amber'] if g > b + 30 and g > 60 else TEXT['red']
    return TEXT['blue']
def bg_map(v):
    v = v.strip()
    m = re.match(r'rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([\d.]+)\s*\)', v)
    if m:
        r, g, b, a = int(m[1]), int(m[2]), int(m[3]), float(m[4])
        if min(r, g, b) >= 190 and a >= .15:
            if max(r, g, b) - min(r, g, b) > 20:   # tinted (red/green/blue/amber) light fill: keep the hue, darken
                return f'rgba({r},{g},{b},{min(.14, a*.3):.2f})'
            return f'rgba(255,255,255,{min(.14, max(.04, a*.18)):.2f})'
        return None
    m = re.match(r'#([0-9a-fA-F]{3,6})\b', v)
    if m and lum('#' + m[1])[0] > .85: return 'rgba(255,255,255,.12)'
    return None
rules = []
for sel, body in re.findall(r'([^{}@]+)\{([^{}]*)\}', src):
    sel = ' '.join(sel.split())
    if not sel or sel.startswith(('from', 'to', '0%', '100%')) or ':root' in sel or sel in ('html', 'body'): continue
    decl = []
    for prop, val in re.findall(r'(background(?:-color)?|color|border(?:-color)?)\s*:\s*([^;]+)', body):
        if prop.startswith('background'):
            nv = bg_map(val.split(' ')[0] if val.startswith('#') else val)
            if 'var(--dark)' in val: decl.append('color:#1f1a14')
            if nv: decl.append(f'background:{nv}')
        elif prop == 'color':
            m = re.match(r'\s*(#[0-9a-fA-F]{3,6})\b', val)
            if m and 'var(--dark)' not in body:
                nv = text_map(m[1])
                if nv: decl.append(f'color:{nv}')
        elif prop.startswith('border'):
            m = re.search(r'rgba\(\s*255\s*,\s*255\s*,\s*255\s*,\s*([\d.]+)\)|#fff\b', val)
            if m: decl.append('border-color:rgba(255,255,255,.12)')
    if decl:
        sels = ', '.join('html.dark ' + s.strip() for s in sel.split(',') if s.strip() and not s.strip().startswith('html'))
        if sels: rules.append(f'{sels} {{ {"; ".join(dict.fromkeys(decl))}; }}')
block = '/* AUTO-DARK START: generated by gen_dark.py from glass.css, do not edit by hand */\n' + '\n'.join(rules) + '\n/* AUTO-DARK END */'
p = open(out_path).read()
if 'AUTO-DARK START' in p: p = re.sub(r'/\* AUTO-DARK START.*?AUTO-DARK END \*/', lambda _: block, p, flags=re.S)
else: p = p.replace('/* ---------- 6. Dark mode', block + '\n\n/* ---------- 6. Dark mode', 1)
open(out_path, 'w').write(p); print(len(rules), 'rules')
